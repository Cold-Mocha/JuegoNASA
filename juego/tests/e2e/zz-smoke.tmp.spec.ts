import { test, expect } from '@playwright/test';
import { startMission, watchConsole } from './helpers';
const hold = async (page: import('@playwright/test').Page, key: string, ms: number) => { await page.keyboard.down(key); await page.waitForTimeout(ms); await page.keyboard.up(key); };
test('afuera', async ({ page }) => {
  test.setTimeout(90_000);
  const problems = watchConsole(page);
  await page.addInitScript(() => localStorage.setItem('michinautas:progress:v1', JSON.stringify({ best: {}, achievements: [], readEntries: [], tutorialDone: true })));
  await startMission(page, { mission: 'huerto-lunar' });
  await page.waitForTimeout(800);
  await hold(page, 's', 1300);
  await hold(page, 'a', 110);
  await hold(page, 's', 2600);
  await page.waitForTimeout(300);
  await page.screenshot({ path: '/tmp/claude-1000/-home-fohwa-Documents-JuegoNASA/df6a4bf5-cdcb-4026-a5ee-c7b10a007106/scratchpad/r1-surface.png' });
  await hold(page, 'd', 1900);
  await hold(page, 'w', 250);
  await page.keyboard.press('e');
  await page.waitForTimeout(400);
  await page.screenshot({ path: '/tmp/claude-1000/-home-fohwa-Documents-JuegoNASA/df6a4bf5-cdcb-4026-a5ee-c7b10a007106/scratchpad/r2-panel.png' });
  await page.keyboard.press('e');
  await page.waitForTimeout(700);
  await page.screenshot({ path: '/tmp/claude-1000/-home-fohwa-Documents-JuegoNASA/df6a4bf5-cdcb-4026-a5ee-c7b10a007106/scratchpad/r3-after.png' });
  await page.keyboard.press('Escape');
  await page.waitForTimeout(200);
  await hold(page, 'a', 3000);
  await hold(page, 's', 1600);
  await page.waitForTimeout(300);
  await page.screenshot({ path: '/tmp/claude-1000/-home-fohwa-Documents-JuegoNASA/df6a4bf5-cdcb-4026-a5ee-c7b10a007106/scratchpad/r4-gh.png' });
  expect(problems).toEqual([]);
});
